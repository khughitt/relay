import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const judge = new URL('../tools/codex-subagent-capture/judge-registry.mjs', import.meta.url).pathname;
const R1='root-one',R2='root-two',W='worker';
const handle={platform:'linux',host:'host',bootId:'12345678-1234-1234-8234-123456789abc',pid:4242,start:'1'};
const row=(id,extra={})=>({id:`codex:${id}`,harness:'codex',sessionId:id,scope:'session',process:handle,
  cwd:'/p',repoRoot:null,remote:null,projectKey:'/p',project:'p',state:'idle',updatedAt:0,...extra});
const worker=(extra={})=>row(W,{scope:'worker',root:`codex:${R1}`,state:'working',...extra});
const rows=(...agents)=>Object.fromEntries(agents.map(a=>[a.id,a]));
const step=(event,session,agents,agent)=>({event,payload:{session_id:session,...(agent?{agent_id:agent}:{})},after:{schema:2,agents}});
const initial=()=>[step('SessionStart',R1,rows(row(R1))),step('SubagentStart',R1,rows(row(R1),worker()),W)];
// Snapshots are prescribed, not generated by a second copy of the retirement algorithm.
const finish=(steps,r2=row(R2))=>[...steps,step('SessionEnd',R1,rows(r2)),step('SessionEnd',R2,rows())];
async function verdict(t,steps,{beforeQuit,checkpointIndex,caseName='switch-new',finalAgents=null}={}){
  const out=await mkdtemp(join(tmpdir(),'relay-capture-judge-'));t.after(()=>rm(out,{recursive:true,force:true}));
  await mkdir(join(out,'log'));await writeFile(join(out,'case'),caseName);
  const snapshots=steps.map((s,i)=>({...s.after,generation:'12345678-1234-4234-8234-123456789abc',revision:i+1}));
  let seq=1000000000000000000n;
  for(const [i,s]of steps.entries()){const base=join(out,'log',`${seq++}-${s.event}`);
    await writeFile(`${base}.json`,JSON.stringify({event:s.event,payload:s.payload,env:{},ancestry:[]}));
    await writeFile(`${base}.reply`,'');await writeFile(`${base}.agents.json`,JSON.stringify(snapshots[i]));}
  await writeFile(join(out,'final-agents.json'),JSON.stringify(finalAgents));
  if(beforeQuit!==false){const checkpoint=snapshots[checkpointIndex??steps.findLastIndex(s=>s.event!=='SessionEnd')];
    await writeFile(join(out,'before-quit-agents.json'),JSON.stringify({...checkpoint,...(beforeQuit?{agents:beforeQuit}:{})}));}
  const r=spawnSync(process.execPath,[judge,out],{encoding:'utf8',env:{PATH:process.env.PATH??'',HOME:out}});
  return{status:r.status,stdout:r.stdout,stderr:r.stderr};
}
const passes=r=>{assert.equal(r.status,0,r.stdout+r.stderr);assert.match(r.stdout,/^PASS:/m);assert.doesNotMatch(r.stdout,/^FAIL:/m);};

test('a one-root background run passes',async t=>{
  passes(await verdict(t,[...initial(),step('SubagentStop',R1,rows(row(R1),worker({state:'done'})),W),step('SessionEnd',R1,rows())],{caseName:'background'}));
});
test('a replaced active worker survives until its stop without changing a root',async t=>{
  passes(await verdict(t,finish([...initial(),step('SessionStart',R2,rows(row(R2),worker())),
    step('SubagentStop',R1,rows(row(R2)),W)])));
});
test('an old root SessionEnd during the hold can be the before-quit checkpoint',async t=>{
  passes(await verdict(t,[...initial(),step('SessionStart',R2,rows(row(R2),worker())),
    step('SessionEnd',R1,rows(row(R2))),step('SessionEnd',R2,rows())],{checkpointIndex:3}));
});
test('a worker event after the before-quit checkpoint is still checked independently',async t=>{
  const steps=[...initial(),step('SessionStart',R2,rows(row(R2),worker())),
    step('SubagentStop',R1,rows(row(R2)),W),step('SessionEnd',R2,rows())];
  passes(await verdict(t,steps,{checkpointIndex:2}));
  steps[3].after.agents=rows(row(R2),worker({state:'done'}));
  const r=await verdict(t,steps,{checkpointIndex:2});assert.equal(r.status,1,r.stdout);
  assert.match(r.stdout,/FAIL: .*SubagentStop.*completed replaced worker/);
});
test('a proven start must remove the old root at that publication',async t=>{
  const r=await verdict(t,finish([...initial(),step('SessionStart',R2,rows(row(R1),row(R2),worker())),
    step('Stop',R1,rows(row(R1,{state:'done'}),row(R2),worker()))]));
  assert.equal(r.status,1,r.stdout);assert.match(r.stdout,/FAIL: .*SessionStart.*root-one/);
});
test('a proven start removes a completed old worker even if a later event cleans it',async t=>{
  const r=await verdict(t,finish([...initial(),step('SubagentStop',R1,rows(row(R1),worker({state:'done'})),W),
    step('SessionStart',R2,rows(row(R2),worker({state:'done'}))),step('SubagentStop',R1,rows(row(R2)),W)]));
  assert.equal(r.status,1,r.stdout);assert.match(r.stdout,/FAIL: .*SessionStart.*worker/);
});
test('a missing start labels accepted duplicate roots and done workers',async t=>{
  const r=await verdict(t,finish([...initial(),step('UserPromptSubmit',R2,rows(row(R1),row(R2,{state:'working'}),worker())),
    step('SubagentStop',R1,rows(row(R1),row(R2,{state:'working'}),worker({state:'done'})),W)],row(R2,{state:'working'})));
  passes(r);assert.match(r.stdout,/ACCEPTED: replacement-not-proven-missing-start/);
});
for(const process of [null,{...handle,bootId:null}])test(`unproven start labels accepted duplicates (${process===null?'null handle':'null boot'})`,async t=>{
  const r2=row(R2,{process});const r=await verdict(t,finish([...initial(),step('SessionStart',R2,rows(row(R1),r2,worker())),
    step('SubagentStop',R1,rows(row(R1),r2,worker({state:'done'})),W)],r2));
  passes(r);assert.match(r.stdout,/ACCEPTED: replacement-not-proven-process/);
});
test('a late old-root event and ordinary done worker get an accepted recreation label',async t=>{
  const old=row(R1,{state:'done'}),r2=row(R2);
  const r=await verdict(t,finish([...initial(),step('SessionStart',R2,rows(r2,worker())),step('Stop',R1,rows(old,r2,worker())),
    step('SubagentStop',R1,rows(old,r2,worker({state:'done'})),W)]));
  passes(r);assert.match(r.stdout,/ACCEPTED: root-recreated-after-replacement/);
});
for(const fault of ['scope','root','root-change','cascade','reap'])test(`accepted duplicates do not hide ${fault} failure`,async t=>{
  const r2=row(R2,{state:'working'}),w=worker({state:'done',...(fault==='scope'?{scope:'session'}:{}),...(fault==='root'?{root:`codex:${R2}`}:{})});
  let steps=finish([...initial(),step('UserPromptSubmit',R2,rows(row(R1),r2,worker())),
    step('SubagentStop',R1,rows(row(R1,{...(fault==='root-change'?{updatedAt:1}:{})}),r2,w),W)],r2);
  if(fault==='cascade')steps[steps.length-2].after.agents=rows(row(R1),r2);
  const r=await verdict(t,steps,{finalAgents:fault==='reap'?{agents:rows(row(R1))}:null});
  assert.equal(r.status,1,r.stdout);assert.match(r.stdout,/^FAIL:/m);
});
test('an explicit root resume clears the previous ended status',async t=>{
  const r=await verdict(t,[...initial(),step('SessionEnd',R1,rows()),step('SessionStart',R2,rows(row(R2))),
    step('SessionStart',R1,rows(row(R1))),step('PreToolUse',R1,rows(row(R1),worker()),W),
    step('SubagentStop',R1,rows(row(R1),worker({state:'done'})),W),step('SessionEnd',R1,rows())]);
  passes(r);assert.doesNotMatch(r.stdout,/root-recreated-after-replacement/);
});
test('an explicit return to a retired root is a start, not late recreation',async t=>{
  const r=await verdict(t,[...initial(),step('SessionStart',R2,rows(row(R2),worker())),
    step('SessionStart',R1,rows(row(R1),worker())),step('SubagentStop',R1,rows(row(R1),worker({state:'done'})),W),
    step('SessionEnd',R1,rows())]);
  passes(r);assert.doesNotMatch(r.stdout,/root-recreated-after-replacement/);
});
for(const competing of [true,false])test(`worker events after end are ordinary (competing root ${competing})`,async t=>{
  const afterEnd=competing?rows(row(R2)):rows();
  const steps=[...initial(),step('SessionEnd',R1,rows()),...(competing?[step('SessionStart',R2,afterEnd)]:[]),
    step('PreToolUse',R1,{...afterEnd,...rows(worker())},W),
    step('SubagentStop',R1,competing?afterEnd:rows(worker({state:'done'})),W),
    step('SessionEnd',R1,afterEnd),...(competing?[step('SessionEnd',R2,rows())]:[])];
  passes(await verdict(t,steps,{caseName:competing?'switch-new':'background'}));
});
test('an unrelated process is never required to retire another root',async t=>{
  const r2=row(R2,{process:{...handle,pid:4243}});
  passes(await verdict(t,finish([...initial(),step('SessionStart',R2,rows(row(R1),r2,worker()))],r2)));
});
for(const missing of ['second-root','before-quit'])test(`a named switch missing ${missing} evidence is invalid`,async t=>{
  const steps=missing==='second-root'?[...initial(),step('SessionEnd',R1,rows())]:finish([...initial(),step('SessionStart',R2,rows(row(R2),worker())),step('SubagentStop',R1,rows(row(R2)),W)]);
  const r=await verdict(t,steps,{beforeQuit:missing==='before-quit'?false:undefined});
  assert.equal(r.status,2,r.stdout);assert.match(r.stdout,/^INVALID:/m);
});
